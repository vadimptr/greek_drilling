const ACUTE = '\u0301'
const VOWELS = 'αεηιουω'

const plain = (s: string) => s.normalize('NFD').split(ACUTE).join('')

function stressLast(stem: string): string {
  const d = plain(stem)
  for (let i = d.length - 1; i >= 0; i--) {
    if (VOWELS.includes(d[i])) return (d.slice(0, i + 1) + ACUTE + d.slice(i + 1)).normalize('NFC')
  }
  return stem
}

function firstPlural(present: string, stem: string): string {
  const stressed = stressLast(stem)
  const augment = /^ε[^ιίυύ]/.test(stressed) && !plain(present).startsWith('ε')
  return (augment ? stressed.slice(1) : stressed) + 'αμε'
}

export function conjugate(present: string, aorist: string, plural?: string): AoristVerb['forms'] {
  const stem = aorist.slice(0, -1)
  const we = plural ?? firstPlural(present, stem)
  return [aorist, stem + 'ες', stem + 'ε', we, we.slice(0, -3) + 'ατε', stem + 'αν']
}

function stableId(present: string): number {
  let h = 0x811c9dc5
  for (const ch of present) {
    h ^= ch.codePointAt(0)!
    h = Math.imul(h, 0x01000193) >>> 0
  }
  return 1000 + (h % 1_000_000_000)
}

function parse(group: AoristGroup, raw: string): AoristVerb[] {
  return raw
    .trim()
    .split('\n')
    .map((line) => {
      const [present, aorist, ru, plural] = line.split('|').map((x) => x.trim())
      const forms = aorist.includes(',') ? (aorist.split(',') as AoristVerb['forms']) : conjugate(present, aorist, plural || undefined)
      return { id: LEGACY_IDS[present] ?? stableId(present), present, ru, group, forms }
    })
}

