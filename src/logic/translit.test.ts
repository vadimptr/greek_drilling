import { describe, expect, it } from 'vitest'
import { transliterate } from './translit'

const cases: [string, string][] = [
  ['καλημέρα', 'калиме́ра'],
  ['ευχαριστώ', 'эфхаристо́'],
  ['γεια σου', 'я су'],
  ['το σπίτι', 'то спи́ти'],
  ['αυτός', 'афто́с'],
  ['αύριο', 'а́врио'],
  ['μπίρα', 'би́ра'],
  ['η λάμπα', 'и ла́мба'],
  ['αντίο', 'анди́о'],
  ['η ντομάτα', 'и дома́та'],
  ['γκρι', 'гри'],
  ['το αγγούρι', 'то ангу́ри'],
  ['το ψωμί', 'то псоми́'],
  ['το τζιν', 'то дзин'],
  ['το τσάι', 'то ца́и'],
  ['τα παιδιά', 'та педья́'],
  ['η ελιά', 'и элья́'],
  ['ο κόσμος', 'о ко́змос'],
  ['ναι', 'не'],
  ['το δωμάτιο', 'то дома́тио'],
  ['ο κύριος', 'о ки́риос'],
  ['η καρδιά', 'и кардья́'],
  ['δεν καταλαβαίνω', 'ден каталаве́но'],
  ['η πόλη', 'и по́ли'],
  ['ο άνθρωπος', 'о а́нтропос'],
  ['η Ευρώπη', 'и эвро́пи'],
  ['ο Έλληνας', 'о э́линас'],
  ['το Σάββατο', 'то са́вато'],
  ['εντάξει', 'энда́кси'],
  ['είμαι', 'и́ме'],
  ['τρώω', 'тро́о'],
  ['η γυναίκα', 'и йине́ка'],
  ['γελάω', 'йела́о'],
  ['πώς λέγεται αυτό;', 'по́с ле́йете афто́;'],
  ['με συγχωρείτε', 'ме синхори́те'],
  ['η Πέμπτη', 'и пе́мпти'],
  ['το χωριό', 'то хорьё'],
  ['ο γιος', 'о ёс'],
  ['συγγνώμη', 'сигно́ми'],
  ['γιατί', 'яти́'],
  ['ο εγγονός', 'о энгоно́с'],
  ['χθες', 'хтес'],
  ['ο Μάιος', 'о ма́иос'],
  ['το κρεμμύδι', 'то креми́ди'],
  ['πού', 'пу́'],
  ['η ζάχαρη', 'и за́хари'],
  ['ξέρω', 'ксе́ро'],
  ['το ρολόι', 'то роло́и'],
  ['η γιαγιά', 'и яя́'],
  ['ο θείος', 'о ти́ос'],
  ["γι' αυτό", 'яфто́'],
]

describe('transliterate', () => {
  for (const [el, ru] of cases) {
    it(`${el} → ${ru}`, () => {
      expect(transliterate(el)).toBe(ru)
    })
  }

  it('keeps punctuation and question marks', () => {
    expect(transliterate('τι κάνεις;')).toBe('ти ка́нис;')
  })
})
